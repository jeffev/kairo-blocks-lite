// Scans src/blocks/<category>/<id>.tsx and writes src/blocks/registry.generated.ts.
// Runs automatically before `dev` and `build`; add a block by adding a file.
//
// `meta` is copied from each file's source as a literal (not imported), because a
// value exported from a "use client" module is only a client reference on the server.
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = "src/blocks";
const entries = [];
for (const category of readdirSync(root).sort()) {
  const dir = join(root, category);
  if (!statSync(dir).isDirectory()) continue;
  for (const file of readdirSync(dir).sort()) {
    if (!file.endsWith(".tsx")) continue;
    const id = file.replace(/\.tsx$/, "");
    const source = readFileSync(join(dir, file), "utf8");
    const match = source.match(/export const meta = (\{[\s\S]*?\n\});/);
    if (!match) throw new Error(`${dir}/${file}: missing "export const meta = {...};"`);
    if (!/export default function \w+/.test(source)) throw new Error(`${dir}/${file}: missing default export`);
    const ident = id.replace(/-(\w)/g, (_, c) => c.toUpperCase()).replace(/^\w/, (c) => c.toUpperCase());
    entries.push({ id, category, ident, meta: match[1] });
  }
}

const lines = [
  "// AUTO-GENERATED by scripts/gen-registry.mjs. Do not edit.",
  'import type { BlockEntry } from "./types";',
  "",
  ...entries.map((e) => `import ${e.ident} from "./${e.category}/${e.id}";`),
  "",
  "export const blocks: BlockEntry[] = [",
  ...entries.map(
    (e) => `  {\n    id: "${e.id}",\n    category: "${e.category}",\n    file: "src/blocks/${e.category}/${e.id}.tsx",\n    meta: ${e.meta.replace(/\n/g, "\n    ")},\n    Component: ${e.ident},\n  },`,
  ),
  "];",
  "",
];
writeFileSync(join(root, "registry.generated.ts"), lines.join("\n"));
console.log(`gen-registry: ${entries.length} block(s)`);
